def is_legacy(p) -> bool:
    """True if the project (or the changes) use the group names of version 1.x."""
    return isinstance(p, dict) and any(k in GROUPS for k in p)


def translate_project(p):
    """Copy of a version 1.x project (or of a dict of changes) with the names of version 2."""
    if not is_legacy(p):
        return p
    q = {}
    for g, d in p.items():
        gn = GROUPS.get(g, g)
        if isinstance(d, dict):
            fm = FIELDS.get(gn, {})
            e = {}
            for k, v in d.items():
                kn = fm.get(k, k)
                vm = VALUES.get(gn + "." + kn)
                if vm and isinstance(v, str):
                    v = vm.get(v, v)
                e[kn] = v
            q[gn] = e
        else:
            q[gn] = d
    q.pop("version", None)   # the converted project is in the format of version 2
    return q


